def summarize_latex_matrix(raw_text, group_size=20):
    """
    Parse a LaTeX-like matrix of rows:
    plan n & col2 & col3 & col4 \\
    
    Return one LaTeX line per 20 plans:
    plan start–end & mean2(std2) & mean3(std3) & mean4(std4) \\
    """
    rows = []

    # Parse the latex matrix
    for line in raw_text.strip().splitlines():
        parts = line.split("&")
        if len(parts) != 4:
            continue
        
        # Extract the 3 numeric columns
        nums = [float(x.strip().replace("\\", "")) for x in parts[1:]]
        rows.append(nums)

    rows = np.array(rows)

    output = []

    # Process each block of 20 rows
    for i in range(0, len(rows), group_size):
        block = rows[i:i+group_size]
        start = i + 1
        end   = i + block.shape[0]

        means = block.mean(axis=0)
        stds  = block.std(axis=0, ddof=1)

        # Format:
        # plan X–Y & mean(std) & mean(std) & mean(std) \\
        line = (
            f"plan {start}–{end} & "
            f"{means[0]:.6f} ({stds[0]:.6f}) & "
            f"{means[1]:.6f} ({stds[1]:.6f}) & "
            f"{means[2]:.6f} ({stds[2]:.6f}) \\\\"
        )
        output.append(line)
    
    # Append latex and overall summary
    output.append(r'''\begin{table}[h!]
\centering
\begin{tabular}{lccc}
\hline
Plan & HV & GD & IGD \\
\hline''')
    output.append("all plans &  2.605178 $\pm$ 0.001486 & 0.0 $\pm$ 0.0 & 0.0 $\pm$ 0.0")
    output.append(r'''\hline
\end{tabular}
\caption{Summary of experimental results}
\label{tab:summary}
\end{table}''')

    #save in folder of this file
    output_dir = "../assets/planningProblem/Test-examples/output_data_RQ2_FINAL"
    import os
    os.makedirs(output_dir, exist_ok=True)
    with open(os.path.join(output_dir, "res_summary.txt"), "w") as f:
        f.write("\n".join(output))

    print(output)
    return "\n".join(output)





